CREATE TABLE IF NOT EXISTS stored_files (
    id BINARY(16) NOT NULL PRIMARY KEY,
    organization_id BINARY(16) NOT NULL,
    property_id BINARY(16) NULL,
    uploaded_by_user_id BINARY(16) NOT NULL,
    file_category VARCHAR(40) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    storage_provider VARCHAR(30) NOT NULL DEFAULT 'LOCAL',
    storage_key VARCHAR(500) NOT NULL,
    sha256_checksum VARCHAR(64) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    updated_by VARCHAR(100) NULL,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    status SMALLINT NOT NULL DEFAULT 1,
    audit_tracker_id VARCHAR(64) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_stored_files_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_stored_files_property FOREIGN KEY (property_id) REFERENCES properties(id),
    CONSTRAINT fk_stored_files_uploader FOREIGN KEY (uploaded_by_user_id) REFERENCES users(id),
    INDEX idx_stored_files_org_cat (organization_id, file_category),
    INDEX idx_stored_files_property (property_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS meters (
    id BINARY(16) NOT NULL PRIMARY KEY,
    organization_id BINARY(16) NOT NULL,
    property_id BINARY(16) NOT NULL,
    room_id BINARY(16) NULL,
    bed_id BINARY(16) NULL,
    meter_number VARCHAR(60) NOT NULL,
    meter_label VARCHAR(120) NULL,
    meter_scope VARCHAR(20) NOT NULL DEFAULT 'ROOM',
    unit_rate DECIMAL(10,4) NOT NULL DEFAULT 0.0000,
    fixed_charge DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    split_method VARCHAR(30) NOT NULL DEFAULT 'EQUAL',
    initial_reading DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    last_reading_value DECIMAL(12,2) NULL,
    last_reading_date DATE NULL,
    meter_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    updated_by VARCHAR(100) NULL,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    status SMALLINT NOT NULL DEFAULT 1,
    audit_tracker_id VARCHAR(64) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    active_guard TINYINT GENERATED ALWAYS AS (IF(status <> 9, 1, NULL)) STORED,
    CONSTRAINT fk_meters_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_meters_property FOREIGN KEY (property_id) REFERENCES properties(id),
    CONSTRAINT fk_meters_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT fk_meters_bed FOREIGN KEY (bed_id) REFERENCES beds(id),
    UNIQUE KEY uk_meters_property_number (property_id, meter_number, active_guard),
    INDEX idx_meters_property_scope (property_id, meter_scope, meter_status),
    INDEX idx_meters_room_bed (room_id, bed_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS meter_readings (
    id BINARY(16) NOT NULL PRIMARY KEY,
    organization_id BINARY(16) NOT NULL,
    property_id BINARY(16) NOT NULL,
    meter_id BINARY(16) NOT NULL,
    billing_year INT NOT NULL,
    billing_month INT NOT NULL,
    reading_date DATE NOT NULL,
    previous_value DECIMAL(12,2) NOT NULL,
    current_value DECIMAL(12,2) NOT NULL,
    units_consumed DECIMAL(12,2) NOT NULL,
    rate_per_unit_snapshot DECIMAL(10,4) NOT NULL,
    fixed_charge_snapshot DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    energy_charge DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    additional_charge DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    credit_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    reading_status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
    photo_file_id BINARY(16) NULL,
    unusual_usage BOOLEAN NOT NULL DEFAULT FALSE,
    unusual_usage_reason VARCHAR(255) NULL,
    correction_of_reading_id BINARY(16) NULL,
    meter_reset_applied BOOLEAN NOT NULL DEFAULT FALSE,
    correction_reason TEXT NULL,
    rejection_reason TEXT NULL,
    recorded_by_user_id BINARY(16) NOT NULL,
    approved_by_user_id BINARY(16) NULL,
    approved_at DATETIME(6) NULL,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    updated_by VARCHAR(100) NULL,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    status SMALLINT NOT NULL DEFAULT 1,
    audit_tracker_id VARCHAR(64) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    active_period_guard VARCHAR(90) GENERATED ALWAYS AS (
        IF(reading_status <> 'REJECTED' AND status = 1 AND correction_of_reading_id IS NULL,
           CONCAT(HEX(meter_id), ':', billing_year, '-', billing_month),
           NULL)
    ) STORED,
    CONSTRAINT fk_readings_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_readings_property FOREIGN KEY (property_id) REFERENCES properties(id),
    CONSTRAINT fk_readings_meter FOREIGN KEY (meter_id) REFERENCES meters(id),
    CONSTRAINT fk_readings_photo FOREIGN KEY (photo_file_id) REFERENCES stored_files(id),
    CONSTRAINT fk_readings_correction FOREIGN KEY (correction_of_reading_id) REFERENCES meter_readings(id),
    CONSTRAINT fk_readings_recorder FOREIGN KEY (recorded_by_user_id) REFERENCES users(id),
    CONSTRAINT fk_readings_approver FOREIGN KEY (approved_by_user_id) REFERENCES users(id),
    UNIQUE KEY uk_meter_readings_active_period (active_period_guard),
    INDEX idx_readings_property_period (property_id, billing_year, billing_month, reading_status),
    INDEX idx_readings_meter_date (meter_id, reading_date DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS electricity_bills (
    id BINARY(16) NOT NULL PRIMARY KEY,
    organization_id BINARY(16) NOT NULL,
    property_id BINARY(16) NOT NULL,
    meter_id BINARY(16) NOT NULL,
    reading_id BINARY(16) NOT NULL,
    tenancy_id BINARY(16) NOT NULL,
    tenant_id BINARY(16) NOT NULL,
    room_id BINARY(16) NULL,
    bed_id BINARY(16) NULL,
    invoice_id BINARY(16) NULL,
    bill_number VARCHAR(50) NOT NULL,
    billing_year INT NOT NULL,
    billing_month INT NOT NULL,
    split_method_snapshot VARCHAR(30) NOT NULL,
    share_percentage DECIMAL(6,2) NOT NULL DEFAULT 100.00,
    units_allocated DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    rate_per_unit_snapshot DECIMAL(10,4) NOT NULL,
    energy_charge DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    fixed_charge_share DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    additional_charge_share DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    tax_amount_share DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    credit_share DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    bill_status VARCHAR(20) NOT NULL DEFAULT 'GENERATED',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    updated_by VARCHAR(100) NULL,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    status SMALLINT NOT NULL DEFAULT 1,
    audit_tracker_id VARCHAR(64) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    active_guard TINYINT GENERATED ALWAYS AS (IF(status <> 9, 1, NULL)) STORED,
    active_reading_tenancy_guard VARCHAR(90) GENERATED ALWAYS AS (
        IF(bill_status <> 'CANCELLED' AND status = 1, CONCAT(HEX(reading_id), ':', HEX(tenancy_id)), NULL)
    ) STORED,
    CONSTRAINT fk_ebills_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT fk_ebills_property FOREIGN KEY (property_id) REFERENCES properties(id),
    CONSTRAINT fk_ebills_meter FOREIGN KEY (meter_id) REFERENCES meters(id),
    CONSTRAINT fk_ebills_reading FOREIGN KEY (reading_id) REFERENCES meter_readings(id),
    CONSTRAINT fk_ebills_tenancy FOREIGN KEY (tenancy_id) REFERENCES tenancies(id),
    CONSTRAINT fk_ebills_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT fk_ebills_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT fk_ebills_bed FOREIGN KEY (bed_id) REFERENCES beds(id),
    CONSTRAINT fk_ebills_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id),
    UNIQUE KEY uk_elec_bill_number (organization_id, bill_number, active_guard),
    UNIQUE KEY uk_elec_bill_reading_tenancy (active_reading_tenancy_guard),
    INDEX idx_ebills_property_period (property_id, billing_year, billing_month),
    INDEX idx_ebills_tenant (tenant_id, billing_year, billing_month)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

