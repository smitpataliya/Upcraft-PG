package com.upcraft.stay.reporting.service.impl;

import java.nio.charset.StandardCharsets;
import java.util.Map;
import java.util.Optional;
import java.util.stream.Collectors;

import org.springframework.stereotype.Service;

import com.upcraft.stay.reporting.dto.ReportResponseDTO;
import com.upcraft.stay.reporting.service.CsvExportService;

/**
 * Generates UTF-8 CSV exports including report metadata header, column rows, and totals footer.
 */
@Service
public class CsvExportServiceImpl implements CsvExportService {

    @Override
    public byte[] exportReportCsv(ReportResponseDTO report) {
        StringBuilder builder = new StringBuilder();
        builder.append("Organization,").append(escape(report.organizationName())).append('\n');
        builder.append("Property Scope,").append(escape(report.propertyScopeLabel())).append('\n');
        builder.append("Report,").append(escape(report.title())).append('\n');
        builder.append("Generated By,").append(escape(report.generatedBy())).append('\n');
        builder.append("Generated At (IST),").append(escape(report.generatedAtIst())).append("\n\n");

        builder.append(report.columns().stream().map(this::escape).collect(Collectors.joining(","))).append('\n');
        for (Map<String, Object> row : report.rows()) {
            String line = report.columns().stream()
                    .map(column -> escape(Optional.ofNullable(row.get(column)).map(Object::toString).orElse("")))
                    .collect(Collectors.joining(","));
            builder.append(line).append('\n');
        }

        if (!report.totals().isEmpty()) {
            builder.append('\n').append("Totals\n");
            report.totals().forEach((key, value) ->
                    builder.append(escape(key)).append(',').append(escape(value.toPlainString())).append('\n'));
        }
        return builder.toString().getBytes(StandardCharsets.UTF_8);
    }

    private String escape(String value) {
        String safe = Optional.ofNullable(value).orElse("");
        if (safe.contains(",") || safe.contains("\"") || safe.contains("\n")) {
            return "\"" + safe.replace("\"", "\"\"") + "\"";
        }
        return safe;
    }
}

