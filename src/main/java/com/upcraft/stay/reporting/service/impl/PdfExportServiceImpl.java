package com.upcraft.stay.reporting.service.impl;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.time.ZonedDateTime;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Service;

import com.upcraft.stay.billing.dto.DepositAccountSummaryResponseDTO;
import com.upcraft.stay.billing.dto.DepositTransactionResponseDTO;
import com.upcraft.stay.billing.dto.InvoiceDetailResponseDTO;
import com.upcraft.stay.billing.dto.InvoiceItemResponseDTO;
import com.upcraft.stay.billing.dto.PaymentReceiptResponseDTO;
import com.upcraft.stay.reporting.dto.PublicShareViewResponseDTO;
import com.upcraft.stay.reporting.dto.ReportResponseDTO;
import com.upcraft.stay.reporting.service.PdfExportService;

/**
 * OpenPDF document generator producing clean INR statements, receipts, invoices, and tabular reports.
 */
@Service
public class PdfExportServiceImpl implements PdfExportService {

    private static final DateTimeFormatter IST_FORMAT = DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm 'IST'");
    private static final Color HEADER_BG = new Color(30, 58, 138);
    private static final Font TITLE_FONT = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 15, Color.BLACK);
    private static final Font SUB_FONT = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.DARK_GRAY);
    private static final Font TH_FONT = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.WHITE);
    private static final Font TD_FONT = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.BLACK);
    private static final Font BOLD_FONT = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, Color.BLACK);

    @Override
    public byte[] exportReportPdf(ReportResponseDTO report) {
        return buildPdf(true, document -> {
            addHeader(document, report.organizationName(), report.title(),
                    "Property: " + report.propertyScopeLabel() + " | Generated by: " + report.generatedBy() + " | " + report.generatedAtIst());
            if (!report.columns().isEmpty()) {
                PdfPTable table = new PdfPTable(report.columns().size());
                table.setWidthPercentage(100);
                table.setSpacingBefore(8);
                report.columns().forEach(column -> table.addCell(headerCell(column)));
                for (Map<String, Object> row : report.rows()) {
                    report.columns().forEach(column -> table.addCell(bodyCell(
                            Optional.ofNullable(row.get(column)).map(Object::toString).orElse("")
                    )));
                }
                document.add(table);
            }
            addTotalsBlock(document, report.totals());
        });
    }

    @Override
    public byte[] exportInvoicePdf(String organizationName, InvoiceDetailResponseDTO invoice, String generatedBy) {
        return buildPdf(false, document -> {
            addHeader(document, organizationName, "Tax / Rent Invoice — " + invoice.invoiceNumber(),
                    "Property: " + invoice.propertyName() + " | Tenant: " + invoice.tenantName()
                            + " | Due: " + invoice.dueDate() + " | Generated by: " + generatedBy + " | " + nowIst());
            PdfPTable table = new PdfPTable(4);
            table.setWidthPercentage(100);
            table.setSpacingBefore(8);
            List.of("Description", "Qty", "Unit (INR)", "Total (INR)").forEach(col -> table.addCell(headerCell(col)));
            for (InvoiceItemResponseDTO item : invoice.items()) {
                table.addCell(bodyCell(item.description()));
                table.addCell(bodyCell(item.quantity().toPlainString()));
                table.addCell(bodyCell(item.unitAmount().toPlainString()));
                table.addCell(bodyCell(item.lineTotal().toPlainString()));
            }
            document.add(table);
            addTotalsBlock(document, Map.of(
                    "Total Amount (INR)", invoice.totalAmount(),
                    "Paid Amount (INR)", invoice.paidAmount(),
                    "Balance Due (INR)", invoice.balanceDue()
            ));
        });
    }

    @Override
    public byte[] exportReceiptPdf(String organizationName, PaymentReceiptResponseDTO receipt, String generatedBy) {
        return buildPdf(false, document -> {
            addHeader(document, organizationName, "Payment Receipt — " + receipt.receiptNumber(),
                    "Generated by: " + generatedBy + " | " + nowIst());
            PdfPTable table = new PdfPTable(2);
            table.setWidthPercentage(100);
            table.setSpacingBefore(8);
            addKeyValueRow(table, "Property", receipt.propertyName());
            addKeyValueRow(table, "Tenant", receipt.tenantName() + " (" + receipt.tenantPhone() + ")");
            addKeyValueRow(table, "Invoice Number", receipt.invoiceNumber());
            addKeyValueRow(table, "Payment Date", String.valueOf(receipt.paidAt()));
            addKeyValueRow(table, "Method", receipt.paymentMethod().name());
            addKeyValueRow(table, "Reference", Optional.ofNullable(receipt.referenceNumber()).orElse("—"));
            addKeyValueRow(table, "Amount Paid (INR)", receipt.amountPaid().toPlainString());
            addKeyValueRow(table, "Remaining Invoice Balance (INR)", receipt.invoiceBalanceRemaining().toPlainString());
            document.add(table);
        });
    }

    @Override
    public byte[] exportDepositStatementPdf(
            String organizationName,
            DepositAccountSummaryResponseDTO summary,
            List<DepositTransactionResponseDTO> transactions,
            String generatedBy
    ) {
        return buildPdf(false, document -> {
            addHeader(document, organizationName, "Security Deposit Statement — " + summary.tenantName(),
                    "Property: " + summary.propertyName() + " | Room " + summary.roomNumber() + " Bed " + summary.bedCode()
                            + " | Generated by: " + generatedBy + " | " + nowIst());
            PdfPTable table = new PdfPTable(5);
            table.setWidthPercentage(100);
            table.setSpacingBefore(8);
            List.of("Date", "Type", "Method", "Amount (INR)", "Reason").forEach(col -> table.addCell(headerCell(col)));
            for (DepositTransactionResponseDTO tx : transactions) {
                table.addCell(bodyCell(String.valueOf(tx.transactionDate())));
                table.addCell(bodyCell(tx.transactionType().name()));
                table.addCell(bodyCell(tx.paymentMethod().name()));
                table.addCell(bodyCell(tx.amount().toPlainString()));
                table.addCell(bodyCell(Optional.ofNullable(tx.reason()).orElse("—")));
            }
            document.add(table);
            addTotalsBlock(document, Map.of(
                    "Deposit Collected (INR)", summary.collectedAmount(),
                    "Total Deductions (INR)", summary.deductionsAmount(),
                    "Total Refunded (INR)", summary.refundedAmount(),
                    "Net Balance Held (INR)", summary.heldBalance()
            ));
        });
    }

    @Override
    public byte[] exportPublicSharePdf(PublicShareViewResponseDTO shareView) {
        return buildPdf(false, document -> {
            addHeader(document, shareView.organizationName(), shareView.title(),
                    shareView.propertyName() + " | " + shareView.subtitle() + " | " + nowIst());
            if (!shareView.metadata().isEmpty()) {
                PdfPTable metaTable = new PdfPTable(2);
                metaTable.setWidthPercentage(100);
                metaTable.setSpacingBefore(6);
                shareView.metadata().forEach((key, value) -> addKeyValueRow(metaTable, key, value));
                document.add(metaTable);
            }
            if (!shareView.lineItems().isEmpty()) {
                List<String> keys = List.copyOf(shareView.lineItems().get(0).keySet());
                PdfPTable itemsTable = new PdfPTable(keys.size());
                itemsTable.setWidthPercentage(100);
                itemsTable.setSpacingBefore(8);
                keys.forEach(key -> itemsTable.addCell(headerCell(key)));
                for (Map<String, Object> row : shareView.lineItems()) {
                    keys.forEach(key -> itemsTable.addCell(bodyCell(
                            Optional.ofNullable(row.get(key)).map(Object::toString).orElse("")
                    )));
                }
                document.add(itemsTable);
            }
            addTotalsBlock(document, shareView.totals());
        });
    }

    private byte[] buildPdf(boolean landscape, PdfBodyWriter bodyWriter) {
        try (ByteArrayOutputStream output = new ByteArrayOutputStream()) {
            Document document = new Document(landscape ? PageSize.A4.rotate() : PageSize.A4, 28, 28, 28, 28);
            PdfWriter.getInstance(document, output);
            document.open();
            bodyWriter.write(document);
            document.close();
            return output.toByteArray();
        } catch (Exception exception) {
            throw new IllegalStateException("Failed to render PDF document", exception);
        }
    }

    private void addHeader(Document document, String orgName, String title, String subtitle) throws Exception {
        Paragraph orgParagraph = new Paragraph(orgName, BOLD_FONT);
        Paragraph titleParagraph = new Paragraph(title, TITLE_FONT);
        Paragraph subParagraph = new Paragraph(subtitle, SUB_FONT);
        subParagraph.setSpacingAfter(8);
        document.add(orgParagraph);
        document.add(titleParagraph);
        document.add(subParagraph);
    }

    private void addTotalsBlock(Document document, Map<String, BigDecimal> totals) throws Exception {
        if (totals.isEmpty()) {
            return;
        }
        Paragraph spacer = new Paragraph("Summary Totals", BOLD_FONT);
        spacer.setSpacingBefore(10);
        document.add(spacer);
        PdfPTable table = new PdfPTable(2);
        table.setWidthPercentage(55);
        table.setHorizontalAlignment(Element.ALIGN_LEFT);
        table.setSpacingBefore(4);
        totals.forEach((key, value) -> addKeyValueRow(table, key, value.toPlainString()));
        document.add(table);
    }

    private void addKeyValueRow(PdfPTable table, String key, String value) {
        table.addCell(bodyCell(key));
        table.addCell(bodyCell(Optional.ofNullable(value).orElse("—")));
    }

    private PdfPCell headerCell(String text) {
        PdfPCell cell = new PdfPCell(new Phrase(text, TH_FONT));
        cell.setBackgroundColor(HEADER_BG);
        cell.setPadding(6);
        return cell;
    }

    private PdfPCell bodyCell(String text) {
        PdfPCell cell = new PdfPCell(new Phrase(text, TD_FONT));
        cell.setPadding(5);
        return cell;
    }

    private String nowIst() {
        return ZonedDateTime.now(ZoneId.of("Asia/Kolkata")).format(IST_FORMAT);
    }

    @FunctionalInterface
    private interface PdfBodyWriter {
        void write(Document document) throws Exception;
    }
}
